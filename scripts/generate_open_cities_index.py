"""Generate the committed Open Cities chip index, checksum manifest, and split maps.

Maintainer script, run once. The index and checksums are committed and never regenerated by users:

- ``src/geo_eval_harness/datasets/open_cities_index.csv.gz``: one row per 512 px native-grid chip
  with its train/val/test split, assigned per 500 m geographic block;
- ``src/geo_eval_harness/checksums/open_cities.sha256``: checksums of the upstream files;
- ``figures/open_cities/``: split maps and ``blocks.geojson``, kept local (see
  ``scripts/plot_open_cities_splits.py``).

Steps (``docs/plans/2026-10-09-open-cities-building-segmentation.md``, Design §1):

1. list the tier-1 STAC catalog and download the scenes and labels into ``--data-dir``;
2. lay a native grid of full 512 px chips per scene, anchored at pixel (0, 0);
3. keep chips that are at least 50% valid, measured at 1/16 resolution;
4. compute each chip's building fraction from the repaired labels;
5. assign each chip to a 500 m block in its city's UTM zone;
6. drop chips that overlap a chip already kept from a larger scene of the same city;
7. drop Zanzibar blocks with under 1% building cover;
8. per city, keep the best of 1,000 seeded block shuffles for a 70/10/20 split in both chip
   count and building pixels.

Usage::

    python scripts/generate_open_cities_index.py --data-dir data/open_cities
"""

import argparse
import gzip
import hashlib
import io
import json
import logging
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import geopandas as gpd
import numpy as np
import pandas as pd
import rasterio
import shapely
from pyproj import Transformer
from rasterio.enums import Resampling
from rasterio.windows import Window

from geo_eval_harness.datasets import open_cities
from geo_eval_harness.datasets.open_cities import BASE_URL, CHIP_SIZE, USER_AGENT, is_valid
from geo_eval_harness.download import fetch_open_cities_file

sys.path.insert(0, str(Path(__file__).parent))
from plot_open_cities_splits import plot_splits

logger = logging.getLogger(__name__)

PACKAGE_DIR = Path(open_cities.__file__).parent
CHECKSUM_PATH = PACKAGE_DIR.parent / "checksums" / "open_cities.sha256"
DECIMATION = 16  # valid fraction measured on 32x32 px per chip
MIN_VALID = 0.5
BLOCK_M = 500.0
MAX_OVERLAP = 0.01
ZNZ_MIN_BUILDING = 0.01
TARGET = {"train": 0.7, "val": 0.1, "test": 0.2}
N_SEEDS = 1000
CITY_EPSG = {
    "acc": 32630,
    "dar": 32737,
    "kam": 32636,
    "mon": 32629,
    "nia": 32631,
    "ptn": 32732,
    "znz": 32737,
}


def get_json(url: str) -> dict:
    """Fetch and parse a JSON document from source.coop."""
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request) as response:
        return json.loads(response.read())


def list_scenes() -> list[tuple[str, str]]:
    """Return sorted ``(city, scene)`` pairs from the tier-1 STAC catalog."""
    scenes = []
    for link in get_json(f"{BASE_URL}/catalog.json")["links"]:
        if link["rel"] != "child":
            continue
        city = link["href"].split("/")[1]
        items = get_json(f"{BASE_URL}/{city}/collection.json")["links"]
        scenes.extend(
            (city, item["href"].split("/")[1])
            for item in items
            if item["rel"] == "item" and "-labels" not in item["href"]
        )
    return sorted(scenes)


def valid_fraction(path: Path) -> tuple[np.ndarray, rasterio.Affine, rasterio.crs.CRS, float]:
    """Return the per-chip valid fraction grid of a scene, read from its overviews."""
    with rasterio.open(path) as ds:
        nx, ny = ds.width // CHIP_SIZE, ds.height // CHIP_SIZE
        rgba = ds.read(
            window=Window(0, 0, nx * CHIP_SIZE, ny * CHIP_SIZE),
            out_shape=(4, ny * CHIP_SIZE // DECIMATION, nx * CHIP_SIZE // DECIMATION),
            resampling=Resampling.nearest,
        )
        k = CHIP_SIZE // DECIMATION
        return (
            is_valid(rgba).reshape(ny, k, nx, k).mean(axis=(1, 3)),
            ds.transform,
            ds.crs,
            ds.res[0],
        )


def building_stats(boxes: np.ndarray, label_path: Path, crs: rasterio.crs.CRS) -> tuple:
    """Return the building fraction and label count of each chip box."""
    geoms = shapely.make_valid(gpd.read_file(label_path).to_crs(crs).geometry.values)
    geoms = geoms[~shapely.is_empty(geoms)]
    fraction = np.zeros(len(boxes))
    count = np.zeros(len(boxes), dtype=int)
    if not len(geoms):
        return fraction, count
    box_idx, geom_idx = shapely.STRtree(geoms).query(boxes, predicate="intersects")
    order = np.argsort(box_idx, kind="stable")
    box_idx, geom_idx = box_idx[order], geom_idx[order]
    groups = np.flatnonzero(np.diff(box_idx)) + 1
    for b_idx, g_idx in zip(np.split(box_idx, groups), np.split(geom_idx, groups), strict=True):
        if not len(b_idx):
            continue
        b = b_idx[0]
        clipped = shapely.intersection(geoms[g_idx], boxes[b])
        fraction[b] = shapely.area(shapely.union_all(clipped)) / shapely.area(boxes[b])
        count[b] = len(g_idx)
    return fraction, count


def chips_for_scene(root: Path, city: str, scene: str) -> pd.DataFrame:
    """Return the valid native-grid chips of one scene with their stats and UTM footprints."""
    valid, tr, crs, gsd = valid_fraction(root / city / f"{scene}.tif")
    rows, cols = np.nonzero(valid >= MIN_VALID)
    x0 = tr.c + cols * CHIP_SIZE * tr.a
    y1 = tr.f + rows * CHIP_SIZE * tr.e
    size = CHIP_SIZE * tr.a
    boxes = shapely.box(x0, y1 - size, x0 + size, y1)
    fraction, count = building_stats(boxes, root / city / f"{scene}.geojson", crs)

    cx, cy = x0 + size / 2, y1 - size / 2
    to_city = Transformer.from_crs(crs, f"EPSG:{CITY_EPSG[city]}", always_xy=True)
    ux, uy = to_city.transform(cx, cy)
    lon, lat = Transformer.from_crs(crs, "EPSG:4326", always_xy=True).transform(cx, cy)
    bx, by = np.floor(ux / BLOCK_M).astype(int), np.floor(uy / BLOCK_M).astype(int)
    corners = [
        to_city.transform(x0 + dx * size, y1 - dy * size)
        for dx, dy in ((0, 0), (1, 0), (1, 1), (0, 1))
    ]
    ring = np.stack([np.stack(c, axis=-1) for c in corners], axis=1)  # (n, 4, 2)
    logger.info("%s/%s: %d valid chips", city, scene, len(rows))
    return pd.DataFrame(
        {
            "city": city,
            "scene": scene,
            "gsd_m": round(gsd, 4),
            "col_off": cols * CHIP_SIZE,
            "row_off": rows * CHIP_SIZE,
            "valid_frac": valid[rows, cols].round(4),
            "building_frac": fraction.round(5),
            "n_buildings": count,
            "block": [f"{city}_{a}_{b}" for a, b in zip(bx, by, strict=True)],
            "lon": np.round(lon, 6),
            "lat": np.round(lat, 6),
            "_poly": shapely.polygons(ring) if len(ring) else np.array([]),
        }
    )


def drop_overlaps(chips: pd.DataFrame) -> pd.DataFrame:
    """Drop chips overlapping (> 1% of area) a chip kept from a larger scene of the same city."""
    keep = np.ones(len(chips), dtype=bool)
    for city, group in chips.groupby("city"):
        counts = group.scene.value_counts().sort_index()
        kept: list[np.ndarray] = []
        for scene in counts.sort_values(ascending=False, kind="stable").index:
            rows = group.index[group.scene == scene]
            polys = chips.loc[rows, "_poly"].to_numpy()
            if kept:
                tree = shapely.STRtree(np.concatenate(kept))
                qi, ki = tree.query(polys, predicate="intersects")
                inter = shapely.area(shapely.intersection(polys[qi], tree.geometries[ki]))
                hit = np.unique(qi[inter > MAX_OVERLAP * shapely.area(polys[qi])])
                keep[rows[hit]] = False
                polys = np.delete(polys, hit)
                if len(hit):
                    logger.info("%s/%s: dropped %d overlapping chips", city, scene, len(hit))
            kept.append(polys)
    logger.info("Overlap dedup: dropped %d chips", (~keep).sum())
    return chips[keep]


def drop_empty_zanzibar_blocks(chips: pd.DataFrame) -> tuple[pd.DataFrame, pd.Series]:
    """Drop Zanzibar blocks below 1% mean building fraction; return them with their fraction."""
    zanzibar = chips[chips.city == "znz"].groupby("block").building_frac.mean()
    dropped = zanzibar[zanzibar < ZNZ_MIN_BUILDING].sort_index()
    kept = chips[~chips.block.isin(dropped.index)]
    logger.info("Zanzibar rule: dropped %d blocks, %d chips", len(dropped), len(chips) - len(kept))
    return kept, dropped


def assign_splits(chips: pd.DataFrame) -> tuple[pd.Series, dict[str, int]]:
    """Per city, keep the block shuffle closest to 70/10/20 in chips and building mass.

    Returns:
        The split of every chip, and the chosen shuffle seed per city.
    """
    assignment: dict[str, str] = {}
    seeds: dict[str, int] = {}
    for city, group in chips.groupby("city"):
        blocks = group.groupby("block").agg(n=("building_frac", "size"), m=("building_frac", "sum"))
        n_total = blocks.n.sum()
        best: tuple[float, int, dict[str, str]] | None = None
        for seed in range(N_SEEDS):
            filled = {"test": 0, "val": 0}
            split: dict[str, str] = {}
            for block, row in blocks.sample(frac=1, random_state=seed).iterrows():
                if filled["test"] < TARGET["test"] * n_total:
                    name = "test"
                elif filled["val"] < TARGET["val"] * n_total:
                    name = "val"
                else:
                    name = "train"
                if name != "train":
                    filled[name] += row.n
                split[block] = name
            labels = pd.Series(split)
            if labels.nunique() < len(TARGET):
                continue
            fn = blocks.n.groupby(labels).sum() / n_total
            fm = blocks.m.groupby(labels).sum() / blocks.m.sum()
            cost = sum(abs(fn[k] - v) + abs(fm[k] - v) for k, v in TARGET.items())
            if best is None or cost < best[0]:
                best = (cost, seed, split)
        assert best is not None, f"no shuffle gives {city} all three splits"
        assignment.update(best[2])
        seeds[city] = best[1]
        logger.info("%s: %d blocks, seed %d, cost %.4f", city, len(blocks), best[1], best[0])
    return chips.block.map(assignment), seeds


def write_index(index: pd.DataFrame, seeds: dict[str, int], dropped: pd.Series, path: Path) -> None:
    """Write the gzipped index CSV with a comment header recording how it was made.

    ``mtime=0`` keeps the gzip bytes identical across reruns.
    """
    header = [
        "Open Cities AI Challenge tier-1 chip index; generated by "
        "scripts/generate_open_cities_index.py. Do not edit: changes mean a new dataset version.",
        f"chip_size={CHIP_SIZE} block_m={BLOCK_M:g} min_valid={MIN_VALID} "
        f"max_overlap={MAX_OVERLAP} znz_min_building={ZNZ_MIN_BUILDING} n_seeds={N_SEEDS}",
        "split_seeds: " + " ".join(f"{city}={seed}" for city, seed in seeds.items()),
        "znz_dropped_blocks: " + " ".join(f"{b}={f:.5f}" for b, f in dropped.items()),
    ]
    with (
        path.open("wb") as raw,
        gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as compressed,
        io.TextIOWrapper(compressed, newline="") as stream,
    ):
        stream.writelines(f"# {line}\n" for line in header)
        index.to_csv(stream, index=False, lineterminator="\n")


def write_checksums(root: Path, scenes: list[tuple[str, str]], path: Path) -> None:
    """Write ``sha256  <city>/<file>`` for every upstream file."""
    files = [f"{c}/{s}.{ext}" for c, s in scenes for ext in ("geojson", "tif")]

    def digest(relative: str) -> str:
        with (root / relative).open("rb") as stream:
            return hashlib.file_digest(stream, "sha256").hexdigest()

    with ThreadPoolExecutor(8) as pool:
        digests = list(pool.map(digest, files))
    path.write_text("".join(f"{d}  {f}\n" for d, f in zip(digests, files, strict=True)))


def main() -> None:
    """Run the full pipeline and write the committed outputs."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--data-dir", type=Path, default=Path("data/open_cities"))
    parser.add_argument("--workers", type=int, default=8)
    parser.add_argument("--plot-dir", type=Path, default=Path("figures/open_cities"))
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s")
    root = args.data_dir

    scenes = list_scenes()
    logger.info("%d tier-1 scenes", len(scenes))
    files = [f"{c}/{s}.{ext}" for c, s in scenes for ext in ("geojson", "tif")]
    with ThreadPoolExecutor(4) as pool:
        list(pool.map(lambda f: fetch_open_cities_file(f, root), files))

    with ThreadPoolExecutor(args.workers) as pool:
        chips = pd.concat(pool.map(lambda s: chips_for_scene(root, *s), scenes), ignore_index=True)
    logger.info("Valid chips: %d", len(chips))
    chips = drop_overlaps(chips)
    chips, dropped = drop_empty_zanzibar_blocks(chips)
    chips = chips.drop(columns="_poly")
    chips["split"], seeds = assign_splits(chips)

    index = chips.sort_values(["city", "scene", "row_off", "col_off"]).reset_index(drop=True)
    index.insert(
        0,
        "chip_id",
        [
            f"{c}_{s}_{r}_{q}"
            for c, s, r, q in zip(
                index.city, index.scene, index.row_off, index.col_off, strict=True
            )
        ],
    )
    columns = ["chip_id", "city", "scene", "gsd_m", "col_off", "row_off", "block", "split"]
    columns += ["lon", "lat", "valid_frac", "building_frac", "n_buildings"]
    index = index[columns]
    write_index(index, seeds, dropped, PACKAGE_DIR / open_cities.INDEX_FILE)
    logger.info(
        "\n%s", pd.crosstab(index.city, index.split, margins=True)[["train", "val", "test", "All"]]
    )
    logger.info(
        "\n%s",
        index.groupby("split").agg(
            chips=("chip_id", "size"),
            blocks=("block", "nunique"),
            building_frac=("building_frac", "mean"),
            empty=("building_frac", lambda x: (x == 0).mean()),
        ),
    )

    write_checksums(root, scenes, CHECKSUM_PATH)
    plot_splits(index, dropped, args.plot_dir, data_dir=root)


if __name__ == "__main__":
    main()
